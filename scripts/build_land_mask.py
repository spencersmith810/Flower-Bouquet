"""Convert Natural Earth 1:110m land GeoJSON to a compact 2-degree land mask.

Usage: python3 scripts/build_land_mask.py /path/to/ne_110m_land.geojson
The generated JavaScript is written to stdout. Natural Earth data is public domain.
"""

import json
import sys


def inside_ring(x, y, ring):
    inside = False
    previous = ring[-1]
    for current in ring:
        x1, y1 = previous[:2]
        x2, y2 = current[:2]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            inside = not inside
        previous = current
    return inside


def main():
    with open(sys.argv[1], encoding="utf-8") as source:
        data = json.load(source)
    polygons = []
    for feature in data["features"]:
        geometry = feature["geometry"]
        parts = [geometry["coordinates"]] if geometry["type"] == "Polygon" else geometry["coordinates"]
        for rings in parts:
            outer = rings[0]
            xs, ys = zip(*(point[:2] for point in outer))
            polygons.append((min(xs), min(ys), max(xs), max(ys), rings))
    rows = []
    for row in range(90):
        lat = 89 - row * 2
        chars = []
        for col in range(180):
            lon = -179 + col * 2
            land = False
            for x0, y0, x1, y1, rings in polygons:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and inside_ring(lon, lat, rings[0]):
                    if not any(inside_ring(lon, lat, hole) for hole in rings[1:]):
                        land = True
                        break
            chars.append("1" if land else "0")
        rows.append("".join(chars))
    print("// Natural Earth 1:110m land, public domain. Generated by scripts/build_land_mask.py.")
    print("window.EARTH_LAND_MASK = [")
    for row in rows:
        print(f'  "{row}",')
    print("]; ")


if __name__ == "__main__":
    main()
